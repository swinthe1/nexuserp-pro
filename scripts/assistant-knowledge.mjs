#!/usr/bin/env node
// What the assistant knows about the program itself: every page of the menu (where it is, what it is
// called, its search words) and its ⓘ guide (what it is for, the steps, the usual mistakes, what
// happens after). Written to deploy/worker/app-knowledge.mjs, which the postier searches for the
// app_help tool. Run after changing the menu or a guide:  npm run assistant:knowledge
//   --check  only says whether the file is up to date (exit 1 when it is not)
import fs from 'node:fs'
import path from 'node:path'
import { createServer } from 'vite'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const out = path.join(root, 'deploy/worker/app-knowledge.mjs')
// the app's own modules, loaded the way the app builds them (aliases, the dictionaries' glob)
const vite = await createServer({ root, logLevel: 'error', server: { middlewareMode: true, hmr: false }, appType: 'custom', optimizeDeps: { noDiscovery: true, include: [] } })
const { GUIDES } = await vite.ssrLoadModule('/src/i18n/help/guides.ts')
const { NAV } = await vite.ssrLoadModule('/src/app/nav.ts')
const { t } = await vite.ssrLoadModule('/src/i18n/index.ts')
await vite.close()

const both = (l) => (l ? { sq: l.sq, en: l.en } : undefined)
const pages = []
const seen = new Set()
for (const s of NAV) {
  const section = t(s.title || s.label)
  for (const it of s.items) {
    const key = it.href.split('?')[0]
    const g = GUIDES[key]
    seen.add(key)
    pages.push({
      path: it.href, title: t(it.label), title_en: it.label.split('|')[0], section, perm: it.perm,
      keywords: it.keywords || [],
      ...(g ? { what: both(g.what), steps: g.steps.map(both), mistakes: (g.mistakes || []).map(both), after: both(g.after),
                related: (g.related || []).map((r) => ({ href: r.href, label: r.label.sq })) } : {}),
    })
  }
}
// pages with a guide that are not in the menu (a document, the till screen…)
for (const [key, g] of Object.entries(GUIDES)) {
  if (seen.has(key)) continue
  pages.push({ path: key, title: g.what.sq.split(':')[0].slice(0, 80), section: null, keywords: [],
    what: both(g.what), steps: g.steps.map(both), mistakes: (g.mistakes || []).map(both), after: both(g.after),
    related: (g.related || []).map((r) => ({ href: r.href, label: r.label.sq })) })
}
const text = `// Generated by scripts/assistant-knowledge.mjs from the menu and the page guides. Do not edit by hand.\nexport default ${JSON.stringify(pages)}\n`
if (process.argv.includes('--check')) {
  const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
  if (now !== text) { console.error('deploy/worker/app-knowledge.mjs is out of date: run npm run assistant:knowledge'); process.exit(1) }
  console.log('assistant knowledge up to date:', pages.length, 'pages')
} else {
  fs.writeFileSync(out, text)
  console.log('wrote', path.relative(root, out), pages.length, 'pages,', Math.round(text.length / 1024), 'KB')
}
