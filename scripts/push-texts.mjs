#!/usr/bin/env node
// Writes deploy/worker/push-texts.mjs: the Albanian of what the database says in notifications,
// so the postier can send phone notifications in the person's language.
//   node scripts/push-texts.mjs          (re-run after changing notification texts; i18n-check reminds you)
//   node scripts/push-texts.mjs --check  (exit 1 when the file is out of date)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const dictDir = join(ROOT, 'src/i18n/sq/dict')
const sq = {}
for (const f of readdirSync(dictDir).filter((f) => f.endsWith('.ts')).sort()) Object.assign(sq, (await import(join(dictDir, f))).default)
const { serverTemplates } = await import(join(ROOT, 'src/i18n/sq/server-templates.ts'))

// only what the database can write: exact texts that appear in the migrations, and enum words
const sql = readdirSync(join(ROOT, 'supabase/migrations')).filter((f) => f.endsWith('.sql')).map((f) => readFileSync(join(ROOT, 'supabase/migrations', f), 'utf8')).join('\n')
const exact = {}
for (const [k, v] of Object.entries(sq)) {
  if (k.includes('|')) continue
  if (k.startsWith('enum:') || sql.includes(`'${k.replace(/'/g, "''")}'`)) exact[k] = v
}
const templates = serverTemplates.filter(([en]) => en.replace(/%%/g, '').includes('%'))
const out = `// Generated by scripts/push-texts.mjs from src/i18n/sq. Do not edit by hand.\nexport const exact = ${JSON.stringify(exact, null, 0)}\nexport const templates = ${JSON.stringify(templates, null, 0)}\n`
const file = join(ROOT, 'deploy/worker/push-texts.mjs')
if (process.argv.includes('--check')) {
  const same = existsSync(file) && readFileSync(file, 'utf8') === out
  if (!same) { console.log('deploy/worker/push-texts.mjs is out of date: run node scripts/push-texts.mjs'); process.exit(1) }
} else {
  writeFileSync(file, out)
  console.log(`push-texts: ${Object.keys(exact).length} texts, ${templates.length} templates`)
}
