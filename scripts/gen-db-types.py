#!/usr/bin/env python3
"""
Generate src/lib/database.types.ts (supabase-js `Database` shape) straight from
a Postgres database that has the migrations applied.

  DATABASE_URL=postgres://... python3 scripts/gen-db-types.py > src/lib/database.types.ts

Equivalent to `supabase gen types typescript`, for environments without the
Supabase CLI. Output is deterministic (sorted) so diffs stay readable.
"""
import json
import os
import subprocess
import sys

DB = os.environ.get("DATABASE_URL")
if not DB:
    sys.exit("set DATABASE_URL")

QUERY = r"""
with cols as (
  select c.relname as rel, c.relkind as kind, a.attname as col, a.attnum,
         format_type(a.atttypid, a.atttypmod) as type, t.typcategory as cat,
         (select et.typname from pg_type et where et.oid = t.typelem) as elem,
         t.typname as typname,
         not a.attnotnull as nullable,
         (a.atthasdef or a.attidentity <> '') as has_default,
         a.attgenerated <> '' as generated
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_type t on t.oid = a.atttypid
   where n.nspname = 'public' and c.relkind in ('r','v') and a.attnum > 0 and not a.attisdropped
),
funcs as (
  select p.proname as name,
         coalesce(p.proargnames, '{}') as argnames,
         coalesce(array(select format_type(x, null) from unnest(p.proargtypes) x), '{}') as argtypes,
         p.pronargdefaults as ndefaults,
         p.proretset as retset,
         format_type(p.prorettype, null) as rettype,
         coalesce(p.proallargtypes::regtype[]::text[], '{}') as alltypes,
         coalesce(p.proargmodes::text[], '{}') as modes
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f'
     and format_type(p.prorettype, null) not in ('trigger', 'event_trigger')
),
rels as (
  select c.relname as rel, con.conname as name,
         array(select a.attname from unnest(con.conkey) with ordinality k(n, i) join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.i) as cols,
         r.relname as ref,
         array(select a.attname from unnest(con.confkey) with ordinality k(n, i) join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.i) as refcols,
         exists (select 1 from pg_constraint u where u.conrelid = con.conrelid and u.contype in ('u','p')
                  and u.conkey::int2[] <@ con.conkey::int2[] and con.conkey::int2[] <@ u.conkey::int2[]) as one_to_one
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    join pg_class r on r.oid = con.confrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_namespace rn on rn.oid = r.relnamespace
   where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
)
select json_build_object(
  'rels', (select json_agg(rels order by rel, name) from rels),
  'cols', (select json_agg(cols order by rel, attnum) from cols),
  'funcs', (select json_agg(funcs order by name) from funcs))
"""

raw = subprocess.check_output(["psql", DB, "-tA", "-c", QUERY], text=True)
data = json.loads(raw)

SCALAR = {
    "uuid": "string", "text": "string", "character": "string", "character varying": "string",
    "citext": "string", "date": "string", "timestamp with time zone": "string",
    "timestamp without time zone": "string", "time without time zone": "string", "interval": "string",
    "numeric": "number", "integer": "number", "bigint": "number", "smallint": "number",
    "real": "number", "double precision": "number", "boolean": "boolean",
    "jsonb": "Json", "json": "Json", "bytea": "string", "void": "undefined",
}


def ts_type(pg: str) -> str:
    base = pg.split("(")[0].strip()
    if base.endswith("[]"):
        return f"{ts_type(base[:-2])}[]"
    return SCALAR.get(base, "unknown")


rels: dict = {}
for r in data["rels"] or []:
    rels.setdefault(r["rel"], []).append(r)

tables: dict = {}
views: dict = {}
for c in data["cols"]:
    target = tables if c["kind"] == "r" else views
    target.setdefault(c["rel"], []).append(c)

out = []
w = out.append
w("// Generated by scripts/gen-db-types.py — do not edit by hand.")
w("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]")
w("")
w("export type Database = {")
w("  public: {")
w("    Tables: {")
for name in sorted(tables):
    cols = tables[name]
    w(f"      {name}: {{")
    w("        Row: {")
    for c in cols:
        t = ts_type(c["type"]) + (" | null" if c["nullable"] else "")
        w(f"          {c['col']}: {t}")
    w("        }")
    w("        Insert: {")
    for c in cols:
        if c["generated"]:
            w(f"          {c['col']}?: never")
            continue
        opt = "?" if (c["nullable"] or c["has_default"]) else ""
        t = ts_type(c["type"]) + (" | null" if c["nullable"] else "")
        w(f"          {c['col']}{opt}: {t}")
    w("        }")
    w("        Update: {")
    for c in cols:
        if c["generated"]:
            w(f"          {c['col']}?: never")
            continue
        t = ts_type(c["type"]) + (" | null" if c["nullable"] else "")
        w(f"          {c['col']}?: {t}")
    w("        }")
    if rels.get(name):
        w("        Relationships: [")
        for r in rels[name]:
            cols_ = ", ".join(f'"{c}"' for c in r["cols"])
            refs_ = ", ".join(f'"{c}"' for c in r["refcols"])
            w(f'          {{ foreignKeyName: "{r["name"]}"; columns: [{cols_}]; isOneToOne: {"true" if r["one_to_one"] else "false"}; referencedRelation: "{r["ref"]}"; referencedColumns: [{refs_}] }},')
        w("        ]")
    else:
        w("        Relationships: []")
    w("      }")
w("    }")
w("    Views: {")
for name in sorted(views):
    w(f"      {name}: {{")
    w("        Row: {")
    for c in views[name]:
        w(f"          {c['col']}: {ts_type(c['type'])} | null")
    w("        }")
    w("        Relationships: []")
    w("      }")
w("    }")
w("    Functions: {")
for f in data["funcs"]:
    names = f["argnames"]
    modes = f["modes"]
    in_types = f["argtypes"]
    # IN args are the first len(argtypes) non-OUT/TABLE names
    in_names = [n for i, n in enumerate(names) if not modes or modes[i] in ("i", "b", "v")][: len(in_types)]
    first_default = len(in_types) - f["ndefaults"]
    w(f"      {f['name']}: {{")
    if in_types:
        w("        Args: {")
        for i, (n, t) in enumerate(zip(in_names, in_types)):
            opt = "?" if i >= first_default else ""
            w(f"          {n}{opt}: {ts_type(t)}")
        w("        }")
    else:
        w("        Args: Record<PropertyKey, never>")
    if modes and "t" in modes:
        cols = [(names[i], f["alltypes"][i]) for i, m in enumerate(modes) if m == "t"]
        body = "; ".join(f"{n}: {ts_type(t)} | null" for n, t in cols)
        w(f"        Returns: {{ {body} }}[]")
    else:
        rt = ts_type(f["rettype"])
        w(f"        Returns: {rt}{'[]' if f['retset'] else ''}")
    w("      }")
w("    }")
w("    Enums: Record<string, never>")
w("    CompositeTypes: Record<string, never>")
w("  }")
w("}")
w("")
w("type PublicSchema = Database['public']")
w("export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row']")
w("export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert']")
w("export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update']")
w("export type Views<T extends keyof PublicSchema['Views']> = PublicSchema['Views'][T]['Row']")
w("export type Functions<T extends keyof PublicSchema['Functions']> = PublicSchema['Functions'][T]")
print("\n".join(out))
